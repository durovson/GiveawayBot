    giveaway_id bigint not null references public.giveaways(id) on delete cascade,
    user_id bigint not null references public.users(telegram_id) on delete cascade,
    tickets integer not null default 1 check (tickets >= 1),
    purchased_rp integer not null default 0 check (purchased_rp >= 0),
    consumed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    primary key (giveaway_id, user_id)
);

create index if not exists idx_giveaway_ticket_balances_user
    on public.giveaway_ticket_balances(user_id, giveaway_id);

create or replace function public.consume_finished_giveaway_tickets()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
    if old.status = 'active' and new.status <> 'active' then
        update public.giveaway_ticket_balances
        set tickets = 1, consumed_at = coalesce(consumed_at, now()), updated_at = now()
        where giveaway_id = new.id and consumed_at is null;
    end if;
    return new;
end;
$$;
drop trigger if exists trg_consume_finished_giveaway_tickets on public.giveaways;
create trigger trg_consume_finished_giveaway_tickets
after update of status on public.giveaways
for each row execute function public.consume_finished_giveaway_tickets();

