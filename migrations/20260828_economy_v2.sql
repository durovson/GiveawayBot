create table if not exists public.ticket_offers (
    code text primary key,
    ticket_count integer not null check (ticket_count between 1 and 10),
    price_rp integer not null check (price_rp > 0),
    mode text not null default 'add' check (mode in ('add', 'fill')),
    pricing_mode text not null default 'fixed'
        check (pricing_mode in ('fixed', 'per_ticket')),
    sort_order integer not null default 0,
    active boolean not null default true,
    updated_at timestamptz not null default now()
